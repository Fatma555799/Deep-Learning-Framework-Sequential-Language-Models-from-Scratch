class MLP:
    def __init__(
        self,
        emb_dim1,
        emb_dim2,
        l1_out_features,
        l2_out_features,
        num_epochs,
        learning_rate,
        block_size=3,
        minibatch_size=32,
        loss_update_steps=1000,
        display_train_loss=True,
        seed=2147483647
        ):
          """Constructor for MLP class."""
          # Creating class attributes
          self.emb_dim_1 = emb_dim1
          self.emb_dim_2 = emb_dim2
          self.l1_out_features = l1_out_features
          self.l2_out_features = l2_out_features
          self.num_epochs = num_epochs
          self.learning_rate = learning_rate
          self.block_size = block_size
          self.minibatch_size = minibatch_size
          self.loss_update_steps = loss_update_steps
          self.display_train_loss = display_train_loss
          self.seed = seed

          g = torch.Generator().manual_seed(self.seed) # for reproducibility
          self.C = torch.randn((self.emb_dim_1,self.emb_dim_2), generator=g)
          self.W1=torch.randn((self.block_size*self.emb_dim_2,self.l1_out_features), generator=g)
          self.b1=torch.randn((self.l1_out_features), generator=g)
          self.W2=torch.randn((self.l1_out_features,self.l2_out_features), generator=g)
          self.b2=torch.randn((self.l2_out_features), generator=g)
          self.parameters = [self.C, self.W1, self.b1, self.W2, self.b2]
          self.num_params = sum(p.nelement() for p in self.parameters)

          for p in parameters:
            p.requires_grad=True

    def call(self,x,y):
      #forward pass
      emb=self.C[x]
      h= torch.tanh(emb.view(-1,emb.shape[-1]*emb.shape[-2])@ self.W1+self.b1)
      logits= h @ self.W2 + self.b2
      loss=F.cross_entropy(logits, y)
      return loss

    def fit(self,x,y):
      loss_per_epoch = {}
      epoch_counter = notebook.tqdm(range(self.num_epochs))
      for k in epoch_counter:
          #mini batches
          xi=torch.randint(0,x.shape[0],(self.minibatch_size,))
          loss=self(x[xi],y[xi])
          if self.display_train_loss and ((k % self.loss_update_steps == 0) or (k == self.num_epochs-1)):
              epoch_counter.set_postfix({"train_loss": loss.item()})
          # Adding a loss computed to the history
          loss_per_epoch[f"epoch_{k+1}"] = loss.item()
          #backward pass
          for p in parameters:
            p.grad=None
          loss.backward()
          #update
          for p in parameters:
            p.data-=self.learning_rate*p.grad
      self.history = loss_per_epoch
